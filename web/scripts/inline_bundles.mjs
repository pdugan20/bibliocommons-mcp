#!/usr/bin/env node
/**
 * Build each `web/*.html` entry via Vite's programmatic API and emit
 * `src/bibliocommons_mcp/_ui_bundles.py` with one HTML constant per
 * entry. Mirrors clickwheel's setup.
 *
 * Why programmatic + Promise.allSettled instead of N `vite build` CLI
 * calls: Vite cold-start is ~5-7s of Node + plugin loading, paid per
 * call. Running everything inside one Node process amortizes that to
 * ~0.5s total. Same output, no plugin surgery — vite-plugin-singlefile
 * is single-input by design.
 *
 * Output format is a Python module: each bundle becomes
 *   FOO_HTML = "<html string>"
 * plus a UI_BUNDLES dict mapping filename → constant for lookup.
 * Strings are emitted as Python double-quoted literals using a
 * hand-rolled escaper because JSON's Unicode-line-separator escapes
 * differ from Python's source rules.
 *
 * Custom `injectLoadingBg` plugin: injects the card's background color
 * as an inline style on <html>/<head> so iOS doesn't paint white for
 * the first ~100ms while the iframe initializes. Borrowed from rewind.
 *
 * Run via `make build-web` or `cd web && npm run build:bundles`.
 */
import { build } from "vite";
import react from "@vitejs/plugin-react";
import { viteSingleFile } from "vite-plugin-singlefile";
import {
  readFileSync,
  writeFileSync,
  readdirSync,
  statSync,
  unlinkSync,
  existsSync,
} from "node:fs";
import { dirname, join, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(webDir, "..");
const distDir = join(webDir, "dist");
const outFile = join(
  repoRoot,
  "src",
  "bibliocommons_mcp",
  "_ui_bundles.py",
);

const entries = readdirSync(webDir).filter((name) => {
  if (!name.endsWith(".html")) return false;
  const full = join(webDir, name);
  if (!statSync(full).isFile()) return false;
  return true;
});

if (!entries.length) {
  console.error(`No .html entries found in ${webDir}`);
  process.exit(1);
}

// Drop orphan .html in dist/ from bundles since deleted, so they don't
// ride along into _ui_bundles.py.
if (existsSync(distDir)) {
  const want = new Set(entries);
  for (const f of readdirSync(distDir)) {
    if (f.endsWith(".html") && !want.has(f)) {
      unlinkSync(join(distDir, f));
    }
  }
}

/**
 * Inject the card's background color as an inline style on <html> and
 * a <style> block in <head> so the iframe paints the right color
 * immediately during document parse, before any JS runs. Without this,
 * iOS Safari flashes a white background for ~100ms during cold mount.
 *
 * Borrowed from rewind/mcp-server/scripts/inline-bundles.mjs.
 */
const injectLoadingBg = {
  name: "inject-loading-bg",
  transformIndexHtml(html) {
    const css =
      "html, body { background: light-dark(#fcfcfa, #272726); }";
    return html
      .replace(
        "<html",
        '<html style="background: light-dark(#fcfcfa, #272726)"',
      )
      .replace("</head>", `<style>${css}</style></head>`);
  },
};

const t0 = Date.now();

const results = await Promise.allSettled(
  entries.map((entry) =>
    build({
      root: webDir,
      plugins: [react(), injectLoadingBg, viteSingleFile()],
      logLevel: "warn",
      build: {
        outDir: distDir,
        emptyOutDir: false,
        rollupOptions: { input: join(webDir, entry) },
      },
    }),
  ),
);

const failures = results
  .map((r, i) =>
    r.status === "rejected" ? { entry: entries[i], reason: r.reason } : null,
  )
  .filter(Boolean);
if (failures.length) {
  for (const f of failures) {
    console.error(`\n[build:bundles] FAILED ${f.entry}:`);
    console.error(f.reason?.stack ?? f.reason);
  }
  process.exit(1);
}

// U+2028 / U+2029 are valid Python source chars but JavaScript regex
// literals can't hold them without breaking tokenization in older
// Node — build via the RegExp constructor with hex-escaped patterns.
const RE_LINE_SEP = new RegExp("\\u2028", "g");
const RE_PARA_SEP = new RegExp("\\u2029", "g");

function pyDoubleQuoted(s) {
  // Python 3 source files are UTF-8 — leave non-ASCII inline, escape
  // only what would break a double-quoted string literal.
  return (
    '"' +
    s
      .replace(/\\/g, "\\\\")
      .replace(/"/g, '\\"')
      .replace(/\n/g, "\\n")
      .replace(/\r/g, "\\r")
      .replace(/\t/g, "\\t")
      .replace(RE_LINE_SEP, "\\u2028")
      .replace(RE_PARA_SEP, "\\u2029") +
    '"'
  );
}

function toConstName(filename) {
  return (
    basename(filename, ".html")
      .toUpperCase()
      .replace(/[^A-Z0-9]+/g, "_")
      .replace(/^_|_$/g, "") + "_HTML"
  );
}

const built = readdirSync(distDir).filter((f) => f.endsWith(".html"));
built.sort();

const lines = [
  '"""Auto-generated by web/scripts/inline_bundles.mjs — do not edit.',
  "",
  "Re-run `make build-web` to regenerate from `web/*.html` entries.",
  '"""',
  "",
  "from __future__ import annotations",
  "",
];

const manifest = [];
for (const f of built) {
  const html = readFileSync(join(distDir, f), "utf8");
  const name = toConstName(f);
  lines.push(`${name} = ${pyDoubleQuoted(html)}`);
  lines.push("");
  manifest.push({ file: f, name, size: html.length });
}

lines.push("UI_BUNDLES: dict[str, str] = {");
for (const { file, name } of manifest) {
  lines.push(`    ${pyDoubleQuoted(file)}: ${name},`);
}
lines.push("}");
lines.push("");

writeFileSync(outFile, lines.join("\n"));

const elapsed = ((Date.now() - t0) / 1000).toFixed(2);
console.log(`\nBuilt ${entries.length} entries in ${elapsed}s.`);
console.log(`Wrote ${outFile}:`);
for (const { file, size } of manifest) {
  console.log(`  - ${file}: ${size.toLocaleString()} chars`);
}
